// Builds the Netlify deployment: generated migrations module + bundled functions.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { build } from 'esbuild';
import { execSync } from 'node:child_process';
execSync('node scripts/build-engine.mjs', { stdio: 'inherit' });

const migs = readdirSync('migrations').filter((f) => f.endsWith('.sql')).sort().map((f) => [f, readFileSync(`migrations/${f}`, 'utf8')]);
writeFileSync('src/netlify/migrations.generated.ts', `// generated by scripts/build-netlify.mjs — do not edit\nexport const MIGRATIONS: [string, string][] = ${JSON.stringify(migs, null, 1)};\n`);

rmSync('netlify/functions', { recursive: true, force: true });
mkdirSync('netlify/functions', { recursive: true });
const entries = {
  api: `import { api } from '../../src/netlify/netlify-functions';\nexport default api;\nexport const config = { path: '/api/*' };\n`,
  'cron-daily': `import { daily } from '../../src/netlify/netlify-functions';\nexport default daily;\nexport const config = { schedule: '0 5 * * *' };\n`,
  'cron-weekly': `import { weekly } from '../../src/netlify/netlify-functions';\nexport default weekly;\nexport const config = { schedule: '0 6 * * 1' };\n`,
};
mkdirSync('netlify/entries', { recursive: true });
for (const [name, code] of Object.entries(entries)) {
  writeFileSync(`netlify/entries/${name}.ts`, code);
  await build({
    entryPoints: [`netlify/entries/${name}.ts`], outfile: `netlify/functions/${name}.mjs`, bundle: true, platform: 'node', format: 'esm', target: 'node20',
    banner: { js: "import { createRequire as __cr } from 'module'; const require = __cr(import.meta.url);" },
    logLevel: 'error', legalComments: 'none',
  });
}
console.log('Netlify functions built:', Object.keys(entries).join(', '));
