export function setLang(l) {
  if (!DICT[l]) return;
  lang = l;
  try { localStorage.setItem('h360_lang', l); } catch {}
  applyDir();
}
export function applyDir() {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
}
